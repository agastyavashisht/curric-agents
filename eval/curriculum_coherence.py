"""
Computes the curriculum-coherence score:
  (a) prerequisite edge-consistency of a generated topic sequence
      against the domain's prerequisite graph
  (b) LLM-as-judge coherence score (FR-12): an LLM rates the generated
      topic sequence on a 1-5 scale for pedagogical soundness, grounded
      difficulty progression, and prerequisite respect
  (c) objective alignment: TF-IDF cosine similarity between each topic's
      stated learning objective and what the Content agent actually generated

Supports all 5 domains via --domain flag.

Usage:
    python -m eval.curriculum_coherence --domain python_programming
    python -m eval.curriculum_coherence --domain all
    python -m eval.curriculum_coherence --domain python_programming --sequence variables_datatypes,strings,operators_expressions
"""
import argparse
import json
import os


DOMAIN_GRAPH_FILES = {
    "python_programming": "data/prerequisite_graph.json",
    "ml_basics":          "data/ml_basics_graph.json",
    "signal_processing":  "data/signal_processing_graph.json",
    "physiology_basics":  "data/physiology_graph.json",
    "data_analysis":      "data/data_analysis_graph.json",
}

# â”€â”€ LLM-as-judge prompt (FR-12) â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
_COHERENCE_JUDGE_PROMPT = """You are an expert curriculum designer reviewing an AI-generated
learning sequence for a student.

Domain: {domain}
Topic sequence generated by the AI planner: {sequence}
Prerequisite graph (topic -> required prior topics): {prereqs}
Student mastery at planning time (0=none, 1=mastered): {mastery}

Rate this sequence on a scale of 1-5 across three dimensions:
1. Prerequisite respect    (5=all prereqs satisfied, 1=many violations)
2. Difficulty progression  (5=smooth low-to-high, 1=random or too steep)
3. Mastery gap prioritisation (5=weakest topics correctly appear first, 1=ignored mastery)

Respond ONLY as JSON:
{{"prerequisite_score": <1-5>, "difficulty_score": <1-5>, "mastery_score": <1-5>,
  "mean_score": <float 1-5>, "rationale": "<one sentence>"}}
No markdown fences.
"""


def _graph_path(domain: str) -> str:
    if domain not in DOMAIN_GRAPH_FILES:
        raise ValueError(
            f"Unknown domain '{domain}'. "
            f"Valid options: {list(DOMAIN_GRAPH_FILES.keys())} or 'all'"
        )
    path = DOMAIN_GRAPH_FILES[domain]
    if not os.path.exists(path):
        raise FileNotFoundError(f"Graph file not found: {path}")
    return path


# â”€â”€ (a) edge consistency â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
def edge_consistency(sequence: list, domain: str = "python_programming") -> dict:
    """Checks that every prerequisite edge in the graph is respected by the sequence."""
    with open(_graph_path(domain), "r", encoding="utf-8") as f:
        topics = json.load(f)["topics"]

    position = {t: i for i, t in enumerate(sequence)}
    total = respected = 0

    for topic, info in topics.items():
        for prereq in info.get("prerequisites", []):
            if topic not in position or prereq not in position:
                continue
            total += 1
            if position[prereq] < position[topic]:
                respected += 1

    fraction = respected / total if total > 0 else 1.0
    return {
        "domain":           domain,
        "edges_checked":    total,
        "edges_respected":  respected,
        "edge_consistency": round(fraction, 4),
    }


# â”€â”€ (b) LLM-as-judge (FR-12) â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
def llm_coherence_judge(
    sequence: list,
    domain: str,
    mastery: dict | None = None,
) -> dict:
    """
    Asks the LLM to rate the sequence on 3 pedagogical dimensions (1-5 each).
    Returns the raw scores plus the LLM's rationale for the paper.
    Stores the raw model response for human-agreement cross-check (NFR auditability).
    """
    try:
        from src.config import get_llm, extract_content, _strip_fences
    except ImportError:
        return {"error": "src.config not importable â€” run from project root"}

    with open(_graph_path(domain), "r", encoding="utf-8") as f:
        topics = json.load(f)["topics"]

    prereqs = {t: topics[t].get("prerequisites", []) for t in sequence if t in topics}
    mastery_sub = {t: round(mastery.get(t, 0.0), 2) for t in sequence} if mastery else {}

    prompt = _COHERENCE_JUDGE_PROMPT.format(
        domain=domain,
        sequence=json.dumps(sequence),
        prereqs=json.dumps(prereqs),
        mastery=json.dumps(mastery_sub),
    )

    try:
        llm = get_llm("planner")   # planner temperature 0.2 â€” deterministic
        resp = llm.invoke(prompt)
        raw  = _strip_fences(extract_content(resp))
        result = json.loads(raw)
        result["raw_judge_response"] = raw   # stored for human cross-check
        result["domain"]   = domain
        result["sequence"] = sequence
        return result
    except Exception as e:
        return {
            "error":    str(e),
            "domain":   domain,
            "sequence": sequence,
        }


# â”€â”€ (c) objective alignment â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
def objective_alignment(
    content_log_path: str = "results/generated_content.jsonl",
    domain_filter: str | None = None,
) -> dict:
    """
    TF-IDF cosine similarity between each topic's learning objective and
    the explanation the Content agent generated. Pure numpy â€” no scipy.
    """
    if not os.path.exists(content_log_path):
        return {"error": f"content log not found: {content_log_path}"}

    rows = []
    with open(content_log_path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            rec = json.loads(line)
            if domain_filter and rec.get("domain") != domain_filter:
                continue
            rows.append(rec)

    if not rows:
        return {"error": "no content rows (run a session first)"}

    try:
        from src.utils import tfidf_cosine
    except ImportError:
        return {"error": "src.utils not importable â€” run from project root"}

    similarities = []
    for row in rows:
        if not row.get("explanation") or not row.get("objective"):
            continue
        sim = tfidf_cosine(row["explanation"], row["objective"])
        similarities.append(sim)

    if not similarities:
        return {"error": "no valid explanation/objective pairs found"}

    return {
        "domain_filter":          domain_filter or "all",
        "n_content_items":        len(similarities),
        "mean_objective_alignment": round(sum(similarities) / len(similarities), 4),
        "min_alignment":          round(min(similarities), 4),
        "max_alignment":          round(max(similarities), 4),
    }


# â”€â”€ combined score â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
def coherence_score(
    edge_result: dict,
    alignment_result: dict,
    judge_result: dict | None = None,
    weight_edges: float     = 0.4,
    weight_alignment: float = 0.3,
    weight_judge: float     = 0.3,
) -> float | None:
    """
    Combined coherence score (0-1):
      40% prerequisite edge consistency
      30% objective alignment (TF-IDF)
      30% LLM judge mean score (normalised to 0-1 from 1-5 scale)
    If judge result is unavailable, redistributes weights to edge + alignment.
    """
    ec = edge_result.get("edge_consistency")
    oa = alignment_result.get("mean_objective_alignment")
    if ec is None or oa is None:
        return None

    if judge_result and "mean_score" in judge_result:
        judge_norm = (judge_result["mean_score"] - 1) / 4   # 1-5 â†’ 0-1
        score = weight_edges * ec + weight_alignment * oa + weight_judge * judge_norm
    else:
        # No judge result â€” split weight equally between edge and alignment
        w = weight_edges + weight_judge / 2
        a = weight_alignment + weight_judge / 2
        score = w * ec + a * oa

    return round(score, 4)


# â”€â”€ multi-session helpers â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
def sequences_from_content_log(content_log_path: str) -> dict:
    """Recover taught topic order per (student_id, domain) from Content logs."""
    sequences = {}
    if not os.path.exists(content_log_path):
        return sequences
    with open(content_log_path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            rec = json.loads(line)
            key   = (rec.get("student_id"), rec.get("domain"))
            topic = rec.get("topic")
            if not key[0] or not key[1] or not topic:
                continue
            seq = sequences.setdefault(key, [])
            if topic not in seq:
                seq.append(topic)
    return sequences


def edge_consistency_from_content_log(
    content_log_path: str = "results/generated_content.jsonl",
    domain_filter: str | None = None,
) -> dict:
    sequences = sequences_from_content_log(content_log_path)
    per = []
    for (sid, domain), seq in sequences.items():
        if domain_filter and domain != domain_filter:
            continue
        if len(seq) < 2:
            continue
        r = edge_consistency(seq, domain=domain)
        r["student_id"] = sid
        per.append(r)
    if not per:
        return {"error": "not enough multi-topic sequences in content log"}
    mean_ec = sum(p["edge_consistency"] for p in per) / len(per)
    return {
        "n_sequences":          len(per),
        "mean_edge_consistency": round(mean_ec, 4),
        "per_sequence":         per,
    }


def run_all_domains(
    content_log: str = "results/generated_content.jsonl",
    run_judge: bool = False,
) -> dict:
    """Run all coherence metrics for every domain."""
    results: dict = {}
    for domain in DOMAIN_GRAPH_FILES:
        results[domain] = objective_alignment(content_log, domain_filter=domain)
    results["all_domains"]      = objective_alignment(content_log)
    results["edge_consistency"] = edge_consistency_from_content_log(content_log)

    if run_judge:
        # Run LLM judge on a sample sequence from the log (first student found)
        seqs = sequences_from_content_log(content_log)
        if seqs:
            (sid, domain), seq = next(iter(seqs.items()))
            results["llm_judge"] = llm_coherence_judge(seq, domain)

    align = results["all_domains"]
    edge  = results["edge_consistency"]
    judge = results.get("llm_judge")
    if "mean_objective_alignment" in align and "mean_edge_consistency" in edge:
        results["combined_coherence_score"] = coherence_score(
            {"edge_consistency": edge["mean_edge_consistency"]},
            align,
            judge_result=judge,
        )
    return results


if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="Curriculum coherence evaluation"
    )
    parser.add_argument("--domain",      default="python_programming",
                        help="Domain key or 'all'")
    parser.add_argument("--sequence",    default=None,
                        help="Comma-separated topic IDs")
    parser.add_argument("--content_log", default="results/generated_content.jsonl")
    parser.add_argument("--judge",       action="store_true",
                        help="Also run LLM-as-judge scoring (uses one LLM call)")
    args = parser.parse_args()

    result: dict = {}

    if args.domain == "all":
        result = run_all_domains(args.content_log, run_judge=args.judge)
    else:
        if args.sequence:
            seq = args.sequence.split(",")
            result["edge_consistency"] = edge_consistency(seq, domain=args.domain)
            if args.judge:
                result["llm_judge"] = llm_coherence_judge(seq, args.domain)

        align = objective_alignment(args.content_log, domain_filter=args.domain)
        result["objective_alignment"] = align

        if "edge_consistency" in result:
            result["combined_coherence_score"] = coherence_score(
                result["edge_consistency"],
                align,
                judge_result=result.get("llm_judge"),
            )

    print(json.dumps(result, indent=2))


